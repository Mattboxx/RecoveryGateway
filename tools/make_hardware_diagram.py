def page_block():
    figure = (f'<figure class="diagram hw-diagram" id="hw-diagram">\n'
              f'  <svg class="hw" viewBox="0 0 {W} {H}" width="{W}" height="{H}" role="group" '
              f'aria-label="Hardware diagram: choose a part to read about it">{drawing(True)}</svg>\n'
              f'  <figcaption>Choose a part of the diagram to read what it does and how it is tested.</figcaption>\n'
              f'</figure>\n')
    items = []
    for key in ORDER:
        p = PARTS[key]
        st = (f' <span class="hw-status hw-status-{p["status"]}">{STATUS_TEXT[p["status"]]}</span>'
              if p['status'] else '')
        href, text = p['link']
        items.append(f'  <section class="hw-detail" id="hw-d-{key}" data-part="{key}">'
                     f'<h2>{p["title"]}{st}</h2><p>{p["body"]}</p>'
                     f'<p><a href="{href}">{text}</a></p></section>')
    details = '<div class="hw-details" aria-live="polite">\n' + '\n'.join(items) + '\n</div>\n'
    return f'{START}\n{figure}{details}{END}'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--check', action='store_true', help='fail if the generated files are out of date')
    args = ap.parse_args()
    svg = static_svg()
    text = PAGE.read_text(encoding='utf-8')
    i, j = text.find(START), text.find(END)
    if i < 0 or j < i:
        sys.exit(f'{PAGE}: hw-diagram markers missing')
    new = text[:i] + page_block() + text[j + len(END):]
    if args.check:
        stale = [str(p) for p, want in ((SVG_OUT, svg), (PAGE, new))
                 if p.read_text(encoding='utf-8').replace('\r\n', '\n') != want.replace('\r\n', '\n')]
        if stale:
            sys.exit('out of date: ' + ', '.join(stale))
        print('hardware diagram up to date')
        return
    SVG_OUT.write_text(svg, encoding='utf-8', newline='\n')
    PAGE.write_text(new, encoding='utf-8', newline='\n')
    print('wrote', SVG_OUT.relative_to(ROOT), 'and', PAGE.relative_to(ROOT))


if __name__ == '__main__':
    main()
