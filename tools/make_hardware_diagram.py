def t(x, y, s, cls='hw-m', anchor='start'):
    a = '' if anchor == 'start' else f' text-anchor="{anchor}"'
    return f'<text class="{cls}" x="{x}" y="{y}"{a}>{html.escape(s)}</text>'


def card(x, y, w, h, opt=False):
    return f'<rect class="{"hw-opt" if opt else "hw-box"}" x="{x}" y="{y}" width="{w}" height="{h}" rx="10"/>'


def badge(x, y):
    label = WARN.upper()
    w = 9 + 7.4 * len(label)
    return (f'<rect class="hw-badge-warn" x="{x}" y="{y}" width="{w:.0f}" height="20" rx="10"/>'
            + t(x + w / 2, y + 14, label, 'hw-badge-t', 'middle'))


def wire(d, cls='hw-wire'):
    return f'<path class="{cls}" d="{d}"/>'


def part(key, inner, interactive):
    if not interactive:
        return f'<g>{inner}</g>'
    return (f'<g class="hw-part" data-part="{key}" role="button" tabindex="0" '
            f'aria-label="{html.escape(PARTS[key]["label"])}" aria-controls="hw-d-{key}">{inner}</g>')


