"""Write the build identity header without forcing a CMake reconfigure."""
from pathlib import Path
import re
import subprocess
import sys


def git_identity(directory: Path) -> str:
    def git(*args: str) -> str:
        return subprocess.check_output(
            ["git", "-C", str(directory), *args], text=True, stderr=subprocess.DEVNULL
        ).strip()

    try:
        if Path(git("rev-parse", "--show-toplevel")).resolve() != directory.resolve():
            return "unknown"
        revision = git("rev-parse", "--short=12", "HEAD")
        if not re.fullmatch(r"[0-9a-f]{12}", revision):
            return "unknown"
        dirty = git("status", "--porcelain", "--untracked-files=no")
    except (OSError, subprocess.CalledProcessError):
        return "unknown"
    return revision + ("-dirty" if dirty else "")


def write_identity(root: Path, output: Path) -> None:
    header = (
        "/* Generated by tools/build_identity.py. */\n"
        "#pragma once\n"
        f'#define MTG_BUILD_COMMIT "{git_identity(root)}"\n'
        f'#define MTG_MICROLINK_COMMIT "{git_identity(root / "external/microlink")}"\n'
    )
    if output.is_file() and output.read_text(encoding="ascii") == header:
        return
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(header, encoding="ascii")


if __name__ == "__main__":
    write_identity(Path(sys.argv[1]), Path(sys.argv[2]))
